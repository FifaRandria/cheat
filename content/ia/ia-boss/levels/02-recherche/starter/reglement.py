REGLEMENT = """
## Adhésion
L'adhésion coûte 20 euros par an et donne accès à tous les outils de la Boîte.
Les mineurs peuvent adhérer avec l'accord écrit d'un parent.

## Emprunts
Un membre peut emprunter trois outils au maximum en même temps.
La durée d'un prêt est de sept jours. Elle peut être prolongée une fois de sept jours si personne n'a réservé l'outil.

## Caution
Une caution de 50 euros est demandée pour les outils électroportatifs. Elle est rendue au retour de l'outil en bon état.

## Retards
En cas de retard, une relance est envoyée par courriel. Après trois retards dans l'année, le membre ne peut plus emprunter pendant un mois.

## Casse
Un outil cassé doit être signalé au retour. L'usure normale n'est pas facturée ; une casse due à une mauvaise utilisation est facturée au prix de la réparation.

## Horaires
La Boîte est ouverte le mercredi de 17 h à 19 h et le samedi de 10 h à 12 h.
"""
